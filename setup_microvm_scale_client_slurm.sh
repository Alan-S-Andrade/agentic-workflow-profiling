#!/usr/bin/env bash
# Rootless GH200/Vista setup for swebench_microvm_scale_experiment.py.
# Run inside a Slurm allocation with readable/writable /dev/kvm.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER_IP="${1:-128.110.220.114}"
CH_VERSION="v53.0"
CH_KERNEL_VERSION="ch-release-v6.16.9-20260508"
ASSETS="$ROOT/microvm-assets"
ROOTFS_TREE="$ASSETS/rootfs-tree"
ROOTFS_IMAGE="$ASSETS/replay-rootfs.img"

if [[ -z "${SLURM_JOB_ID:-}" ]]; then
  echo "Run this setup from a Slurm job; submit slurm/run_microvm_scale_client.slurm from a login node." >&2
  exit 1
fi
python3 - "$SERVER_IP" <<'PY'
import ipaddress, sys
try:
    ipaddress.IPv4Address(sys.argv[1])
except ValueError:
    raise SystemExit("server address must be an IPv4 address")
PY
if [[ "$(uname -m)" != aarch64 || ! -r /dev/kvm || ! -w /dev/kvm ]]; then
  echo "This job needs an aarch64 GH200 node with readable and writable /dev/kvm." >&2
  ls -l /dev/kvm 2>&1 || true
  exit 1
fi

module load tacc-apptainer
for tool in curl sha256sum mkfs.ext4 truncate python3 numactl taskset; do
  command -v "$tool" >/dev/null || { echo "Required compute-node tool missing: $tool" >&2; exit 1; }
done

export DEBIAN_FRONTEND=noninteractive
export TMPDIR="${TMPDIR:-/tmp/$USER-microvm-$SLURM_JOB_ID}"
export APPTAINER_TMPDIR="${APPTAINER_TMPDIR:-$TMPDIR/apptainer-tmp}"
export APPTAINER_CACHEDIR="${APPTAINER_CACHEDIR:-$TMPDIR/apptainer-cache}"
mkdir -p "$TMPDIR" "$APPTAINER_TMPDIR" "$APPTAINER_CACHEDIR" \
  "$ROOT/.tools" "$ASSETS" "$ROOT/traces"

case "$(uname -m)" in
  aarch64) CH_ASSET=cloud-hypervisor-static-aarch64 ;;
esac
CH_BIN="$ROOT/.tools/cloud-hypervisor"
if [[ ! -x "$CH_BIN" ]] || ! "$CH_BIN" --version 2>/dev/null | grep -q "cloud-hypervisor $CH_VERSION"; then
  curl -fL --retry 3 \
    "https://github.com/cloud-hypervisor/cloud-hypervisor/releases/download/$CH_VERSION/$CH_ASSET" \
    -o "$CH_BIN.tmp"
  chmod 0755 "$CH_BIN.tmp"
  mv -f "$CH_BIN.tmp" "$CH_BIN"
fi

KERNEL="$ASSETS/vmlinuz"
if [[ ! -s "$KERNEL" ]]; then
  curl -fL --retry 3 \
    "https://github.com/cloud-hypervisor/linux/releases/download/$CH_KERNEL_VERSION/Image-arm64" \
    -o "$KERNEL.tmp"
  mv -f "$KERNEL.tmp" "$KERNEL"
fi
printf '%s  %s\n' \
  f192b510eea1c710cbc439d716bb0573c223fc463dbe3e6523788a2b7ef62850 "$CH_BIN" \
  69d1b1235381ec50f1b45cf771a7dff4a9013d452833ab34682d6283e2114010 "$KERNEL" | sha256sum -c -

if [[ ! -d "$ROOTFS_TREE" ]]; then
  BUILD_TREE="$TMPDIR/scale-client-rootfs"
  apptainer build --fakeroot --sandbox "$BUILD_TREE" "$ROOT/microvm_scale_client_guest.def"
  cp -a "$BUILD_TREE" "$ROOTFS_TREE"
fi
for required in usr/bin/python3 usr/bin/busybox; do
  if [[ ! -e "$ROOTFS_TREE/$required" ]]; then
    echo "Guest root filesystem is incomplete: $ROOTFS_TREE/$required is missing." >&2
    echo "Repair or remove $ROOTFS_TREE and rerun this setup job." >&2
    exit 1
  fi
done

ENDPOINT="http://$SERVER_IP:8080/v1/inference"
if curl -fsS --max-time 10 "http://$SERVER_IP:8080/healthz" \
  | python3 -c 'import json,sys; d=json.load(sys.stdin); print("Server health:", "ok" if d.get("ok") else "unhealthy", "instances:", d.get("instances", "unknown"))'; then
  :
else
  echo "Inference server health check failed at $SERVER_IP:8080." >&2
  exit 1
fi

cat > "$ROOT/cloud-hypervisor.env" <<ENV
# Generated by setup_microvm_scale_client_slurm.sh in Slurm job $SLURM_JOB_ID.
MICROVM_REPO_ROOT="$ROOT"
export PATH="\$MICROVM_REPO_ROOT/.tools:\$PATH"
export CLOUD_HYPERVISOR_BIN="\$MICROVM_REPO_ROOT/.tools/cloud-hypervisor"
export MICROVM_KERNEL="\$MICROVM_REPO_ROOT/microvm-assets/vmlinuz"
export MICROVM_ROOTFS="\$MICROVM_REPO_ROOT/microvm-assets/replay-rootfs.img"
export MICROVM_INFERENCE_ENDPOINT="$ENDPOINT"
export MICROVM_VSOCK_DIR="/tmp/$USER-microvm-vsock-$SLURM_JOB_ID"
export MICROVM_USE_VSOCK_PROXY=1
ENV
chmod 0644 "$ROOT/cloud-hypervisor.env"
mkdir -p "/tmp/$USER-microvm-vsock-$SLURM_JOB_ID"

cat <<EOF
Rootless GH200 client setup is ready.
Endpoint: $ENDPOINT
Cloud Hypervisor: $CH_BIN
Guest kernel: $KERNEL
Guest rootfs tree: $ROOTFS_TREE
KVM: $(ls -l /dev/kvm)
EOF
